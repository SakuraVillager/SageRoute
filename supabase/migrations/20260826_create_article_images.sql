-- Semantic image metadata for the initial Article reading surfaces.
-- Binary files remain in an external image host or Supabase Storage; this table
-- stores their stable URL, intended display role, and attribution metadata.
create table if not exists public.article_images (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public."Article" (id) on delete cascade,
  role text not null check (role in ('cover', 'featured', 'poster')),
  image_url text not null check (length(trim(image_url)) > 0),
  alt_text text,
  source text,
  photographer_name text,
  attribution_url text,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default timezone('utc', now()),
  unique (article_id, role)
);

create index if not exists article_images_article_id_sort_idx
  on public.article_images (article_id, sort_order);

alter table public.article_images enable row level security;

grant select on table public.article_images to anon, authenticated;

drop policy if exists "Public can read article images" on public.article_images;
create policy "Public can read article images"
  on public.article_images
  for select
  to anon, authenticated
  using (true);

