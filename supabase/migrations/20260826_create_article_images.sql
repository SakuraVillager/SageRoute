  article.id,
  image_seed.role,
  image_seed.image_url,
  image_seed.alt_text,
  'unsplash',
  image_seed.attribution_url
from image_seed
join public."Article" as article on article.title = image_seed.article_title
on conflict (article_id, role) do update
set
  image_url = excluded.image_url,
  alt_text = excluded.alt_text,
  source = excluded.source,
  attribution_url = excluded.attribution_url;
